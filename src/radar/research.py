"""Cross-family research registry and post-discovery confirmation.

The registry is a finite, auditable set of hypotheses generated by the existing
research engines. It never creates orders; only globally adjusted and confirmed
results are eligible for signal notifications.
"""
from __future__ import annotations

from datetime import date

import numpy as np
import pandas as pd

from . import evidence as E
from . import investments as I
from . import store
from .settings import sources

COLS = ["family", "key", "n", "p", "local_q", "global_q", "effect", "hit", "local_status",
        "status", "first_pass", "confirm_n", "confirmed", "asof"]
FAMILIES = {
    "evidence": ("evidence", "key"),
    "invest_evidence": ("invest_evidence", "category"),
    "invest_subgroups": ("invest_subgroups", "key"),
    "insider_evidence": ("insider_evidence", "category"),
    "insider_subgroups": ("insider_subgroups", "key"),
    "basket_evidence": ("basket_evidence", "key"),
    "trade_evidence": ("trade_evidence", "key"),
    "sector_confluence_evidence": ("sector_confluence_evidence", "key"),
}
COUNT_COLS = ("n", "n_clusters")
EFFECT_COLS = ("post_mean", "mean_car_60", "mean_alpha_sector", "mean")
HIT_COLS = ("consistency", "hit_60", "hit", "oos_hit")


def _number(row: dict, columns: tuple[str, ...]) -> float:
    for col in columns:
        try:
            value = float(row.get(col))
            if np.isfinite(value):
                return value
        except (TypeError, ValueError):
            continue
    return np.nan


def _text(value: object) -> str:
    return "" if value is None or pd.isna(value) else str(value)


def _hypotheses(frames: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rows = []
    for family, (table, key_col) in FAMILIES.items():
        frame = frames.get(table)
        if frame is None or frame.empty or key_col not in frame or "p" not in frame:
            continue
        for row in frame.to_dict("records"):
            try:
                p = float(row.get("p"))
            except (TypeError, ValueError):
                continue
            if not np.isfinite(p) or not 0 <= p <= 1:
                continue
            confirmed = _text(row.get("confirmed", "")).lower()
            status = _text(row.get("status", "unclear")) or "unclear"
            rows.append({
                "family": family,
                "key": str(row[key_col]),
                "n": int(_number(row, COUNT_COLS)) if np.isfinite(_number(row, COUNT_COLS)) else 0,
                "p": p,
                "local_q": _number(row, ("q",)),
                "effect": _number(row, EFFECT_COLS),
                "hit": _number(row, HIT_COLS),
                "local_status": status,
                "_native_confirmed": confirmed,
                "_native_first_pass": _text(row.get("first_pass", "")),
                "_native_confirm_n": _number(row, ("confirm_n",)),
            })
    return pd.DataFrame(rows)


def _basket_fresh(key: str, after: str, returns: pd.DataFrame) -> pd.DataFrame:
    if returns.empty or "date" not in returns or "group" not in returns:
        return pd.DataFrame()
    if key == "all":
        frame = returns
    elif key.startswith("all@"):
        frame = returns[returns["selector"] == key.split("@", 1)[1]]
    elif ":all@" in key:
        family, selector = key.split(":all@", 1)
        frame = returns[returns["group"].astype(str).str.startswith(f"{family}:")
                        & (returns["selector"] == selector)]
    else:
        frame = returns[returns["group"].astype(str) == key]
    return frame[frame["date"].astype(str) > after].copy()


def _trade_fresh(key: str, after: str, returns: pd.DataFrame) -> tuple[pd.DataFrame, str]:
    if returns.empty or "date" not in returns:
        return pd.DataFrame(), ""
    group, _, horizon = key.rpartition("|")
    try:
        int(horizon)
    except ValueError:
        return pd.DataFrame(), ""
    frame = returns[returns["date"].astype(str) > after].copy()
    if group == "news":
        frame = frame[frame["news"].astype(str).str.lower().isin(["true", "1"])]
    elif group == "nonews":
        frame = frame[~frame["news"].astype(str).str.lower().isin(["true", "1"])]
    elif group != "all":
        return pd.DataFrame(), ""
    return frame, f"car_h{horizon}"


def _fresh_stats(family: str, key: str, after: str,
                 returns: dict[str, pd.DataFrame]) -> tuple[int, float, float, float, float]:
    frame = pd.DataFrame()
    raw_col = ""
    extra_col = ""
    if family == "basket_evidence":
        frame = _basket_fresh(key, after, returns.get("basket_returns", pd.DataFrame()))
        value_col = "car_0_60"
    elif family == "trade_evidence":
        frame, value_col = _trade_fresh(key, after, returns.get("trade_returns", pd.DataFrame()))
        raw_col = value_col.replace("car_", "raw_")
    elif family == "sector_confluence_evidence":
        frame = returns.get("sector_confluence_returns", pd.DataFrame())
        frame = frame[(frame["key"].astype(str) == key) & (frame["date"].astype(str) > after)] if not frame.empty else frame
        value_col, raw_col, extra_col = "alpha_sector", "raw_return", "excess_spy"
    else:
        return 0, np.nan, np.nan, np.nan, np.nan
    if frame.empty or value_col not in frame:
        return 0, np.nan, np.nan, np.nan, np.nan
    x = pd.to_numeric(frame[value_col], errors="coerce")
    valid = frame.assign(car_0_60=x, car_0_5=x, car_0_20=x).dropna(subset=["car_0_60"])
    stats = I._stats(valid, sources()["corp_invest"]["gate"])
    n = int(stats["n"])
    mean, hit = float(stats["mean_car_60"]), float(stats["hit_60"])
    raw_mean = np.nan
    if raw_col and raw_col in frame:
        raw_mean = float(pd.to_numeric(frame[raw_col], errors="coerce").groupby(frame["date"]).mean().mean())
    extra_mean = np.nan
    if extra_col and extra_col in frame:
        extra_mean = float(pd.to_numeric(frame[extra_col], errors="coerce").groupby(frame["date"]).mean().mean())
    return n, mean, hit, raw_mean, extra_mean


def build_registry(frames: dict[str, pd.DataFrame], returns: dict[str, pd.DataFrame] | None = None,
                   previous: pd.DataFrame | None = None, asof: str | None = None) -> pd.DataFrame:
    """Apply one BH correction to the complete, predeclared research family."""
    rows = _hypotheses(frames)
    if rows.empty:
        return pd.DataFrame(columns=COLS)
    rows["global_q"] = E._bh(rows["p"])
    old = {}
    if previous is not None and not previous.empty:
        old = {(str(r["family"]), str(r["key"])): r for r in previous.to_dict("records")}
    ret = returns or {}
    conf_n = int(sources().get("research", {}).get("confirm_n", 12))
    global_q = float(sources().get("research", {}).get("global_q", 0.10))
    today = asof or date.today().isoformat()
    statuses, first_pass, confirms, confirmed = [], [], [], []
    for r in rows.to_dict("records"):
        family, key, local = r["family"], r["key"], r["local_status"]
        prev = old.get((family, key), {})
        fp = _text(prev.get("first_pass", "")) or r["_native_first_pass"]
        count, done = 0, ""
        candidate = local in {"proven", "promising", "candidate", "confirmed"}
        global_ok = r["global_q"] <= global_q
        if not candidate:
            result = local
            fp = ""
        elif not global_ok:
            result = "filtered"
            fp = ""
        elif family == "evidence":
            result = "confirmed" if local == "proven" else "candidate"
            done = "yes" if result == "confirmed" else "no"
        elif family in {"invest_evidence", "insider_evidence"}:
            native = r["_native_confirmed"]
            if native == "yes":
                result, done = "confirmed", "yes"
            elif native == "failed":
                result, done = "failed", "failed"
            else:
                result, done = "candidate", "no"
        elif family in {"invest_subgroups", "insider_subgroups"}:
            result = "confirmed" if local == "confirmed" else "candidate"
            done = "yes" if result == "confirmed" else "no"
        else:
            result = "candidate"
            if not fp:
                fp = today
            count, mean, hit, raw_mean, extra_mean = _fresh_stats(family, key, fp, ret)
            if count >= conf_n:
                raw_ok = family not in {"trade_evidence", "sector_confluence_evidence"} or (
                    np.isfinite(raw_mean) and raw_mean > 0)
                bench_ok = family != "sector_confluence_evidence" or (np.isfinite(extra_mean) and extra_mean > 0)
                done = "yes" if (mean > 0 and hit >= sources()["corp_invest"]["gate"]["oos_hit"]
                                 and raw_ok and bench_ok) else "failed"
                result = "confirmed" if done == "yes" else "failed"
            else:
                done = "no"
        statuses.append(result)
        first_pass.append(fp)
        native_n = r["_native_confirm_n"]
        confirms.append(count if family in {"basket_evidence", "trade_evidence", "sector_confluence_evidence"} else
                        int(native_n) if np.isfinite(native_n) else 0)
        confirmed.append(done)
    rows["status"], rows["first_pass"], rows["confirm_n"], rows["confirmed"] = statuses, first_pass, confirms, confirmed
    rows["asof"] = today
    return rows.drop(columns=["_native_confirmed", "_native_first_pass", "_native_confirm_n"]).reindex(columns=COLS).sort_values(
        ["global_q", "family", "key"], na_position="last").reset_index(drop=True)


def refresh() -> pd.DataFrame:
    """Refresh the shared registry after every research engine has written its results."""
    frames = {table: store.read(table) for table, _ in FAMILIES.values()}
    returns = {name: store.read(name) for name in
               ("basket_returns", "trade_returns", "sector_confluence_returns")}
    result = build_registry(frames, returns, store.read("research_registry"))
    store.write("research_registry", result)
    return result


def confirmed_keys(family: str) -> set[str]:
    registry = store.read("research_registry")
    if registry.empty:
        return set()
    rows = registry[(registry["family"] == family) & (registry["status"] == "confirmed")]
    return set(rows["key"].astype(str))
